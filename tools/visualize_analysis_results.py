                    ax3_twin = ax3.twinx()
                    ax3_twin.plot(layer_indices, diff, marker='^', color='red', 
                                 label='Difference (Direct - POMP)', linewidth=2, linestyle='--')
                    ax3.set_xlabel('Layer Index')
                    ax3.set_ylabel('CKA', color='black')
                    ax3_twin.set_ylabel('Difference', color='red')
                    ax3.set_title('CKA Comparison & Difference', fontweight='bold')
                    ax3.set_xticks(layer_indices)
                    ax3.set_xticklabels(df_pre_direct['layer'].values, rotation=45, ha='right')
                    ax3.legend(loc='upper left')
                    ax3_twin.legend(loc='upper right')
                    ax3.grid(True, alpha=0.3)
        
