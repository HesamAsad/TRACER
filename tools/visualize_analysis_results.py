    def plot_block_wise_analysis(self):
        """Create block-wise analysis visualizations."""
        param_keys = [k for k in self.data.keys() if 'cka' not in k and 'svcca' not in k]
        if not param_keys:
            print("No parameter metrics found, skipping block-wise analysis")
            return
        
        # Filter to vision transformer blocks only
        fig, axes = plt.subplots(2, 2, figsize=(16, 12))
        
        for idx, key in enumerate(param_keys[:3]):  # Max 3 comparisons
            df = self.data[key]
            
            # Filter to blocks only
            if 'block_idx' in df.columns:
                df_blocks = df[df['block_idx'].notna()].copy()
                
                if len(df_blocks) > 0:
                    row = idx // 2
                    col = idx % 2
                    ax = axes[row, col]
                    
                    # Group by block and submodule
                    pivot_rel_delta = df_blocks.pivot_table(
                        values='relative_delta',
                        index='block_idx',
                        columns='submodule',
                        aggfunc='mean'
                    )
                    
                    # Plot heatmap
                    sns.heatmap(pivot_rel_delta, annot=True, fmt='.3f', cmap='viridis',
                               cbar_kws={'label': 'Relative Delta'}, ax=ax)
                    ax.set_title(f'Relative Delta by Block & Submodule\n({key.replace("_", " ").title()})', 
                               fontweight='bold')
                    ax.set_xlabel('Submodule')
                    ax.set_ylabel('Block Index')
        
        # Summary plot: Average relative delta per block across all comparisons
        ax = axes[1, 1]
        block_means = {}
        for key in param_keys:
            df = self.data[key]
            if 'block_idx' in df.columns:
                df_blocks = df[df['block_idx'].notna()].copy()
                if len(df_blocks) > 0:
                    block_means[key] = df_blocks.groupby('block_idx')['relative_delta'].mean()
        
        if block_means:
            x_pos = np.arange(max(len(bm) for bm in block_means.values()))
            width = 0.25
            for i, (key, means) in enumerate(block_means.items()):
                offset = (i - len(block_means)/2) * width
                ax.bar(x_pos[:len(means)] + offset, means.values, width,
                      label=key.replace('_', ' ').title(), alpha=0.8)
            ax.set_xlabel('Block Index')
            ax.set_ylabel('Mean Relative Delta')
            ax.set_title('Average Relative Delta per Block', fontweight='bold')
            ax.legend()
            ax.grid(True, alpha=0.3, axis='y')
        
        plt.suptitle('Block-Wise Parameter Analysis', fontsize=16, fontweight='bold', y=0.995)
        plt.tight_layout()
        plt.savefig(self.figures_dir / 'block_wise_analysis.png', dpi=300, bbox_inches='tight')
        plt.savefig(self.figures_dir / 'block_wise_analysis.pdf', bbox_inches='tight')
        plt.close()
        print(f"Saved block-wise analysis to {self.figures_dir / 'block_wise_analysis.png'}")
    
