#!/usr/bin/env python3
"""
Comprehensive visualization script for checkpoint analysis results.

This script reads CSV files generated by checkpoint_arch_analysis.py and creates
comprehensive visualizations including:
- Parameter-delta heatmaps and bar charts
- Per-layer CKA/SVCCA trends
- Top-changed layers analysis
- Distribution plots
- Comparative visualizations
"""

import os
import sys
import argparse
from pathlib import Path
from typing import Optional, Dict, List, Tuple
import warnings
warnings.filterwarnings('ignore')

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.gridspec import GridSpec

# Set style
plt.rcParams['figure.dpi'] = 100
plt.rcParams['savefig.dpi'] = 300
plt.rcParams['font.size'] = 10
plt.rcParams['axes.labelsize'] = 12
plt.rcParams['axes.titlesize'] = 14
plt.rcParams['xtick.labelsize'] = 10
plt.rcParams['ytick.labelsize'] = 10
plt.rcParams['legend.fontsize'] = 10

try:
    plt.style.use('seaborn-v0_8-darkgrid')
except:
    plt.style.use('seaborn-darkgrid')

sns.set_palette("husl")


class AnalysisVisualizer:
    """Comprehensive visualizer for checkpoint analysis results."""
    
    def __init__(self, analysis_dir: Path, output_dir: Optional[Path] = None):
        self.analysis_dir = Path(analysis_dir)
        self.tables_dir = self.analysis_dir / "tables"
        self.figures_dir = output_dir if output_dir else (self.analysis_dir / "figures")
        self.figures_dir.mkdir(exist_ok=True, parents=True)
        
        # Load all CSV files
        self.data = self._load_data()
    
    def _load_data(self) -> Dict[str, pd.DataFrame]:
        """Load all CSV files from tables directory."""
        data = {}
        
        # Parameter metrics
        param_files = [
            'param_metrics_pre_vs_direct.csv',
            'param_metrics_pre_vs_pomp.csv',
            'param_metrics_direct_vs_pomp.csv',
        ]
        
        for filename in param_files:
            filepath = self.tables_dir / filename
            if filepath.exists():
                key = filename.replace('.csv', '').replace('param_metrics_', '')
                df = pd.read_csv(filepath)
                # Filter out ln_pre if present (check both key and layer columns)
                if 'key' in df.columns:
                    df = df[~df['key'].str.contains('ln_pre', case=False, na=False)]
                if 'layer' in df.columns:
                    df = df[~df['layer'].str.contains('ln_pre', case=False, na=False)]
                if 'layer_name' in df.columns:
                    df = df[~df['layer_name'].str.contains('ln_pre', case=False, na=False)]
                data[key] = df
                print(f"Loaded {filename}: {len(data[key])} rows (filtered)")
        
        # Per-layer CKA
        cka_files = [
            'per_layer_cka_pre_vs_direct.csv',
            'per_layer_cka_pre_vs_pomp.csv',
            'per_layer_cka_direct_vs_pomp.csv',
        ]
        
        for filename in cka_files:
            filepath = self.tables_dir / filename
            if filepath.exists():
                key = filename.replace('.csv', '').replace('per_layer_cka_', 'cka_')
                df = pd.read_csv(filepath)
                # Filter out ln_pre if present
                if 'layer' in df.columns:
                    df = df[~df['layer'].str.contains('ln_pre', case=False, na=False)]
                if 'layer_name' in df.columns:
                    df = df[~df['layer_name'].str.contains('ln_pre', case=False, na=False)]
                data[key] = df
                print(f"Loaded {filename}: {len(data[key])} rows (filtered)")
        
        # Per-layer SVCCA
        svcca_files = [
            'per_layer_svcca_pre_vs_direct.csv',
            'per_layer_svcca_pre_vs_pomp.csv',
            'per_layer_svcca_direct_vs_pomp.csv',
        ]
        
        for filename in svcca_files:
            filepath = self.tables_dir / filename
            if filepath.exists():
                key = filename.replace('.csv', '').replace('per_layer_svcca_', 'svcca_')
                df = pd.read_csv(filepath)
                # Filter out ln_pre if present
                if 'layer' in df.columns:
                    df = df[~df['layer'].str.contains('ln_pre', case=False, na=False)]
                if 'layer_name' in df.columns:
                    df = df[~df['layer_name'].str.contains('ln_pre', case=False, na=False)]
                data[key] = df
                print(f"Loaded {filename}: {len(data[key])} rows (filtered)")
        
        return data
    
    def plot_parameter_metrics_overview(self):
        """Create comprehensive overview of parameter metrics."""
        if not any(k.startswith('pre_vs') or k.startswith('direct_vs') for k in self.data.keys() if 'cka' not in k and 'svcca' not in k):
            print("No parameter metrics found, skipping parameter overview")
            return
        
        # Filter parameter dataframes
        param_keys = [k for k in self.data.keys() if 'cka' not in k and 'svcca' not in k]
        if not param_keys:
            return
        
        fig = plt.figure(figsize=(16, 12))
        gs = GridSpec(3, 3, figure=fig, hspace=0.3, wspace=0.3)
        
        # 1. Relative delta distribution
        ax1 = fig.add_subplot(gs[0, 0])
        for key in param_keys:
            df = self.data[key]
            if 'relative_delta' in df.columns:
                ax1.hist(df['relative_delta'], bins=50, alpha=0.6, label=key.replace('_', ' ').title(), density=True)
        ax1.set_xlabel('Relative Delta')
        ax1.set_ylabel('Density')
        ax1.set_title('Relative Delta Distribution')
        ax1.legend()
        ax1.set_yscale('log')
        
        # 2. Cosine similarity distribution
        ax2 = fig.add_subplot(gs[0, 1])
        for key in param_keys:
            df = self.data[key]
            if 'cosine_similarity' in df.columns:
                ax2.hist(df['cosine_similarity'], bins=50, alpha=0.6, label=key.replace('_', ' ').title(), density=True)
        ax2.set_xlabel('Cosine Similarity')
        ax2.set_ylabel('Density')
        ax2.set_title('Cosine Similarity Distribution')
        ax2.legend()
        
        # 3. Spectral drift distribution
        ax3 = fig.add_subplot(gs[0, 2])
        for key in param_keys:
            df = self.data[key]
            if 'spectral_drift' in df.columns:
                ax3.hist(df['spectral_drift'], bins=50, alpha=0.6, label=key.replace('_', ' ').title(), density=True)
        ax3.set_xlabel('Spectral Drift')
        ax3.set_ylabel('Density')
        ax3.set_title('Spectral Drift Distribution')
        ax3.legend()
        ax3.set_yscale('log')
        
        # 4. Relative delta by layer type
        ax4 = fig.add_subplot(gs[1, 0])
        if param_keys:
            df = self.data[param_keys[0]]
            if 'relative_delta' in df.columns and 'layer_type' in df.columns:
                all_layer_types = set()
                for key in param_keys:
                    df_temp = self.data[key]
                    if 'layer_type' in df_temp.columns:
                        all_layer_types.update(df_temp['layer_type'].unique())
                
                if all_layer_types:
                    x_pos = np.arange(len(all_layer_types))
                    width = 0.25
                    for i, key in enumerate(param_keys):
                        df_temp = self.data[key]
                        if 'relative_delta' in df_temp.columns and 'layer_type' in df_temp.columns:
                            layer_types = df_temp.groupby('layer_type')['relative_delta'].mean()
                            values = [layer_types.get(lt, 0) for lt in sorted(all_layer_types)]
                            offset = (i - len(param_keys)/2) * width
                            ax4.bar(x_pos + offset, values, width, label=key.replace('_', ' ').title(), alpha=0.8)
                    ax4.set_xlabel('Layer Type')
                    ax4.set_ylabel('Mean Relative Delta')
                    ax4.set_title('Relative Delta by Layer Type')
                    ax4.set_xticks(x_pos)
                    ax4.set_xticklabels(sorted(all_layer_types))
                    ax4.legend()
                    ax4.tick_params(axis='x', rotation=45)
        
        # 5. Cosine similarity by layer type
        ax5 = fig.add_subplot(gs[1, 1])
        if param_keys:
            df = self.data[param_keys[0]]
            if 'cosine_similarity' in df.columns and 'layer_type' in df.columns:
                all_layer_types = set()
                for key in param_keys:
                    df_temp = self.data[key]
                    if 'layer_type' in df_temp.columns:
                        all_layer_types.update(df_temp['layer_type'].unique())
                
                if all_layer_types:
                    x_pos = np.arange(len(all_layer_types))
                    width = 0.25
                    for i, key in enumerate(param_keys):
                        df_temp = self.data[key]
                        if 'cosine_similarity' in df_temp.columns and 'layer_type' in df_temp.columns:
                            layer_types = df_temp.groupby('layer_type')['cosine_similarity'].mean()
                            values = [layer_types.get(lt, 0) for lt in sorted(all_layer_types)]
                            offset = (i - len(param_keys)/2) * width
                            ax5.bar(x_pos + offset, values, width, label=key.replace('_', ' ').title(), alpha=0.8)
                    ax5.set_xlabel('Layer Type')
                    ax5.set_ylabel('Mean Cosine Similarity')
                    ax5.set_title('Cosine Similarity by Layer Type')
                    ax5.set_xticks(x_pos)
                    ax5.set_xticklabels(sorted(all_layer_types))
                    ax5.legend()
                    ax5.tick_params(axis='x', rotation=45)
        
        # 6. Top 20 changed parameters
        ax6 = fig.add_subplot(gs[1, 2])
        for key in param_keys[:1]:  # Just show first comparison
            df = self.data[key]
            if 'relative_delta' in df.columns:
                top_changed = df.nlargest(20, 'relative_delta')
                y_pos = np.arange(len(top_changed))
                ax6.barh(y_pos, top_changed['relative_delta'].values)
                ax6.set_yticks(y_pos)
                # Shorten layer names for display
                labels = [name.split('.')[-1] if '.' in name else name[:30] for name in top_changed['key'].values]
                ax6.set_yticklabels(labels)
                ax6.set_xlabel('Relative Delta')
                ax6.set_title(f'Top 20 Changed Parameters\n({key.replace("_", " ").title()})')
                ax6.invert_yaxis()
        
        # 7. Relative delta vs Cosine similarity scatter
        ax7 = fig.add_subplot(gs[2, 0])
        for key in param_keys:
            df = self.data[key]
            if 'relative_delta' in df.columns and 'cosine_similarity' in df.columns:
                ax7.scatter(df['relative_delta'], df['cosine_similarity'], 
                           alpha=0.5, s=10, label=key.replace('_', ' ').title())
        ax7.set_xlabel('Relative Delta')
        ax7.set_ylabel('Cosine Similarity')
        ax7.set_title('Relative Delta vs Cosine Similarity')
        ax7.legend()
        ax7.set_xscale('log')
        
        # 8. Summary statistics table
        ax8 = fig.add_subplot(gs[2, 1:])
        ax8.axis('off')
        summary_data = []
        for key in param_keys:
            df = self.data[key]
            summary_data.append({
                'Comparison': key.replace('_', ' ').title(),
                'Mean Rel. Delta': f"{df['relative_delta'].mean():.4f}" if 'relative_delta' in df.columns else 'N/A',
                'Mean Cosine Sim.': f"{df['cosine_similarity'].mean():.4f}" if 'cosine_similarity' in df.columns else 'N/A',
                'Mean Spectral Drift': f"{df['spectral_drift'].mean():.4f}" if 'spectral_drift' in df.columns else 'N/A',
                'Total Params': len(df),
            })
        summary_df = pd.DataFrame(summary_data)
        table = ax8.table(cellText=summary_df.values, colLabels=summary_df.columns,
                         cellLoc='center', loc='center', bbox=[0, 0, 1, 1])
        table.auto_set_font_size(False)
        table.set_fontsize(9)
        table.scale(1, 2)
        ax8.set_title('Summary Statistics', fontsize=14, fontweight='bold', pad=20)
        
        plt.suptitle('Parameter Metrics Overview', fontsize=16, fontweight='bold', y=0.995)
        plt.savefig(self.figures_dir / 'parameter_metrics_overview.png', dpi=300, bbox_inches='tight')
        plt.savefig(self.figures_dir / 'parameter_metrics_overview.pdf', bbox_inches='tight')
        plt.close()
        print(f"Saved parameter metrics overview to {self.figures_dir / 'parameter_metrics_overview.png'}")
    
    def plot_per_layer_cka_svcca_comprehensive(self):
        """Create comprehensive per-layer CKA/SVCCA visualizations."""
        cka_keys = [k for k in self.data.keys() if k.startswith('cka_')]
        svcca_keys = [k for k in self.data.keys() if k.startswith('svcca_')]
        
        if not cka_keys and not svcca_keys:
            print("No CKA/SVCCA data found, skipping per-layer analysis")
            return
        
        fig = plt.figure(figsize=(18, 10))
        gs = GridSpec(2, 3, figure=fig, hspace=0.3, wspace=0.3)
        
        # CKA plots
        if cka_keys:
            # Per-layer CKA line plot
            ax1 = fig.add_subplot(gs[0, 0])
            for key in cka_keys:
                df = self.data[key]
                if 'layer' in df.columns and 'cka' in df.columns:
                    # Ensure ln_pre is filtered out
                    df = df[~df['layer'].astype(str).str.contains('ln_pre', case=False, na=False)]
                    layer_names = df['layer'].values
                    layer_indices = range(len(layer_names))
                    ax1.plot(layer_indices, df['cka'].values, marker='o', 
                            label=key.replace('cka_', '').replace('_', ' ').title(), linewidth=2)
            # Set axis labels using the first dataframe
            if cka_keys and 'layer' in self.data[cka_keys[0]].columns:
                df_first = self.data[cka_keys[0]]
                df_first = df_first[~df_first['layer'].astype(str).str.contains('ln_pre', case=False, na=False)]
                layer_names = df_first['layer'].values
                layer_indices = range(len(layer_names))
                ax1.set_xticks(layer_indices)
                ax1.set_xticklabels(layer_names, rotation=45, ha='right')
            ax1.set_xlabel('Layer Index')
            ax1.set_ylabel('CKA')
            ax1.set_title('Per-Layer CKA', fontweight='bold')
            ax1.legend()
            ax1.grid(True, alpha=0.3)
            
            # CKA by layer type (if available)
            ax2 = fig.add_subplot(gs[0, 1])
            for key in cka_keys:
                df = self.data[key]
                if 'layer' in df.columns and 'cka' in df.columns:
                    # Extract layer type from layer name
                    layer_types = []
                    for layer_name in df['layer']:
                        layer_name_lower = str(layer_name).lower()
                        if 'patch' in layer_name_lower or 'embed' in layer_name_lower:
                            layer_types.append('Embedding')
                        elif 'block' in layer_name_lower:
                            try:
                                block_num = int(str(layer_name).split('_')[-1])
                                if block_num < 4:
                                    layer_types.append('Early Blocks')
                                elif block_num < 8:
                                    layer_types.append('Middle Blocks')
                                else:
                                    layer_types.append('Late Blocks')
                            except (ValueError, IndexError):
                                layer_types.append('Middle Blocks')
                        elif 'ln_post' in layer_name_lower or 'final' in layer_name_lower:
                            layer_types.append('Final Layers')
                        else:
                            layer_types.append('Other')
                    
                    df_with_types = df.copy()
                    df_with_types['layer_category'] = layer_types
                    category_means = df_with_types.groupby('layer_category')['cka'].mean()
                    x_pos = np.arange(len(category_means))
                    width = 0.25
                    offset = (cka_keys.index(key) - len(cka_keys)/2) * width
                    ax2.bar(x_pos + offset, category_means.values, width,
                           label=key.replace('cka_', '').replace('_', ' ').title(), alpha=0.8)
            ax2.set_xlabel('Layer Category')
            ax2.set_ylabel('Mean CKA')
            ax2.set_title('CKA by Layer Category', fontweight='bold')
            if cka_keys:
                df = self.data[cka_keys[0]]
                if 'layer' in df.columns:
                    layer_types = []
                    for layer_name in df['layer']:
                        layer_name_lower = str(layer_name).lower()
                        if 'patch' in layer_name_lower or 'embed' in layer_name_lower:
                            layer_types.append('Embedding')
                        elif 'block' in layer_name_lower:
                            try:
                                block_num = int(str(layer_name).split('_')[-1])
                                if block_num < 4:
                                    layer_types.append('Early Blocks')
                                elif block_num < 8:
                                    layer_types.append('Middle Blocks')
                                else:
                                    layer_types.append('Late Blocks')
                            except (ValueError, IndexError):
                                layer_types.append('Middle Blocks')
                        elif 'ln_post' in layer_name_lower or 'final' in layer_name_lower:
                            layer_types.append('Final Layers')
                        else:
                            layer_types.append('Other')
                    df_with_types = df.copy()
                    df_with_types['layer_category'] = layer_types
                    category_means = df_with_types.groupby('layer_category')['cka'].mean()
                    ax2.set_xticks(x_pos)
                    ax2.set_xticklabels(category_means.index)
            ax2.legend()
            ax2.tick_params(axis='x', rotation=45)
            
            # CKA difference plot (Pre vs Direct vs Pre vs POMP)
            ax3 = fig.add_subplot(gs[0, 2])
            if 'cka_pre_vs_direct' in self.data and 'cka_pre_vs_pomp' in self.data:
                df_pre_direct = self.data['cka_pre_vs_direct'].copy()
                df_pre_pomp = self.data['cka_pre_vs_pomp'].copy()
